def build_final_prompt(channel, owner_ids: list[int]) -> str:
    """
    Собирает финальный промпт для канала.

    Логика:
    - Канал владельца (owner_id в owner_ids) → OWNER_PROMPT.
    - Канал юзера → BASE_PROMPT + (дизайнерский, если задан).
    """
    is_owner = channel.owner_id in owner_ids

    if is_owner:
        return OWNER_PROMPT

    parts = [BASE_PROMPT]
    if channel.ai_prompt:
        parts.append(
            "ДОПОЛНИТЕЛЬНЫЕ ТРЕБОВАНИЯ (перекрывают выше, если конфликт):\n"
            + channel.ai_prompt
        )
    return "\n\n".join(parts)


def is_owner_channel(channel, owner_ids: list[int]) -> bool:
    """Проверка — канал владельца."""
    return channel.owner_id in owner_ids
